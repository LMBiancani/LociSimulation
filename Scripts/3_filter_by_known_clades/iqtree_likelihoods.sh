#!/bin/bash
#SBATCH --job-name=iqtree
#SBATCH --partition=uri-cpu
#SBATCH --time=02:00:00
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=30
#SBATCH --mem=8G
#SBATCH --constraint=avx512
#SBATCH --mail-user="biancani@uri.edu"
#SBATCH --mail-type=ALL

# Capture positional arguments and source configuration
random_seed=$1
echo "Random number seed = $random_seed"
set_dir="set_$random_seed"

# Source master parameters script:
vars="/scratch4/workspace/biancani_uri_edu-LociSimulation/LociSimulation/Scripts/variables.sh"
source $vars
echo "Variables sourced into current shell environment:"
cat $vars

# Input alignment directory (generated by 2.4):
Alignments="$out2_4/$set_dir"
# Input constraint trees directory (generated by 3.0):
Constraints="$out3_0/$set_dir"

# Output directory for unconstrained and constrained likelihood runs:
OutDir="$out3_1/$set_dir"
mkdir -p "$OutDir"

# --- Environment Setup ---
module purge
module load uri/main
module load foss/2024a
module load parallel/20240822

# --- Command Factory Function for GNU Parallel ---
run_iqtree() {
    locus_path="$1"
    filename=$(basename "$locus_path")
    locus_id="${filename%.*}"

    const_file="$Constraints/${locus_id}_constraint.newick"

    # Define runs to evaluate
    run_types=("uncon")
    if [ -f "$const_file" ]; then
        run_types+=("con")
    fi

    # Shared execution block
    for run_type in "${run_types[@]}"; do
        out_prefix="$OutDir/${locus_id}_${run_type}"

        # Resume logic: skip if non-empty report exists
        if [ ! -s "${out_prefix}.iqtree" ]; then
            
            # Dynamic argument configuration:
            # - Unconstrained uses '-t BIONJ' to bypass RapidNJ missing-data crashes
            # - Constrained uses '-g' (mutually exclusive with -t BIONJ in IQ-TREE)
            extra_args=()
            if [ "$run_type" = "uncon" ]; then
                extra_args=("-t" "BIONJ")
            elif [ "$run_type" = "con" ]; then
                extra_args=("-g" "$const_file")
            fi

            "$IQTREE" -s "$locus_path" \
                      -m GTR+G \
                      "${extra_args[@]}" \
                      -pre "$out_prefix" \
                      -nt 1 \
                      -redo \
                      -quiet
        fi
    done

    # Post-execution cleanup of intermediate scratch files
    rm -f "$OutDir/${locus_id}_"*".ckp.gz" \
          "$OutDir/${locus_id}_"*".bionj" \
          "$OutDir/${locus_id}_"*".mldist"
}

# Export function and static paths directly into subshell environments
export -f run_iqtree
export IQTREE OutDir Constraints

# Parallel Execution
# Use 'find' with POSIX regex instead of 'ls' to prevent shell ARG_MAX buffer overflows.
# Explicitly forward required environment variables to all subshell workers.
find "$Alignments" -maxdepth 1 -regextype posix-extended -regex '.*\.(fas|fa|fasta)$' | \
    parallel --env IQTREE \
             --env OutDir \
             --env Constraints \
             -j 30 \
             --no-notice \
             run_iqtree {}

echo "IQ-TREE inferences complete. Likelihoods saved in $OutDir"
